#!/usr/bin/env python3
"""gen_code_manifest.py — 生成 MY-CODES/CODE-MANIFEST.tsv（relpath / bytes / sha256 / commit）。

口径：`git ls-files`（tracked 文件，含已 staged 的新文件），排除清单自身。
字节/哈希取 **git index blob**（`git cat-file blob :<rel>`），不是工作树磁盘字节：
这样 `.gitattributes` 的 eol 转换（CRLF/LF）与跨机器 checkout 都不会让清单漂移。
输出写到仓根 `CODE-MANIFEST.tsv`，供 `_Docs/test/structure_check.py` 的 S8 真对账。

用法：
  python -B tools/sync/gen_code_manifest.py          # 重新生成并写盘
  python -B tools/sync/gen_code_manifest.py --check  # 只校验，不写盘（差异即 exit 1）

注意：改了代码要重跑本脚本并一起提交，否则 S8 会报「内容漂移」。
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
MANIFEST = REPO / "CODE-MANIFEST.tsv"
HEADER = ("relpath", "bytes", "sha256", "commit")


def git(*args: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(REPO), *args],
        check=True,
        capture_output=True,
    ).stdout


def tracked_files() -> list[str]:
    raw = git("ls-files", "-z").decode("utf-8", "replace")
    return [p for p in raw.split("\0") if p]


def blob_bytes(rel: str) -> bytes:
    """Index blob 字节（与工作树 eol 无关）。"""
    return git("cat-file", "blob", f":{rel}")


def build() -> str:
    commit = git("rev-parse", "HEAD").decode("ascii", "replace").strip()
    lines = [f"# generated by tools/sync/gen_code_manifest.py from git ls-files; commit={commit}"]
    lines.append("\t".join(HEADER))
    for rel in sorted(tracked_files()):
        if rel == MANIFEST.name:
            continue
        data = blob_bytes(rel)
        lines.append(f"{rel}\t{len(data)}\t{hashlib.sha256(data).hexdigest()}\t{commit[:12]}")
    return "\n".join(lines) + "\n"


def parse_manifest_text(text: str) -> list[tuple[str, str, str]]:
    rows: list[tuple[str, str, str]] = []
    for line in text.splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        parts = line.split("\t")
        if parts[0] == "relpath" or len(parts) < 3:
            continue
        rows.append((parts[0], parts[1].strip(), parts[2].strip()))
    return rows


def parse_manifest(path: Path) -> list[tuple[str, str, str]]:
    return parse_manifest_text(path.read_text(encoding="utf-8"))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="生成 MY-CODES/CODE-MANIFEST.tsv")
    ap.add_argument("--check", action="store_true", help="只校验现有清单，不写盘")
    args = ap.parse_args(argv)

    text = build()
    if args.check:
        if not MANIFEST.is_file():
            print("缺 CODE-MANIFEST.tsv，请先跑 gen_code_manifest.py", file=sys.stderr)
            return 1
        current = {rel: (nbytes, sha) for rel, nbytes, sha in parse_manifest(MANIFEST)}
        fresh = {rel: (nbytes, sha) for rel, nbytes, sha in parse_manifest_text(text)}
        missing = sorted(set(fresh) - set(current))
        extra = sorted(set(current) - set(fresh))
        drift = sorted(rel for rel in set(fresh) & set(current) if fresh[rel] != current[rel])
        if missing or extra or drift:
            print(
                f"CODE-MANIFEST.tsv 过期: 缺项={missing[:3]} 多项={extra[:3]} 漂移={drift[:3]}",
                file=sys.stderr,
            )
            return 1
        print(f"CODE-MANIFEST.tsv 一致（{len(fresh)} files；commit 列不参与校验）")
        return 0

    MANIFEST.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {MANIFEST} ({len(text.splitlines()) - 2} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
